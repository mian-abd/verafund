function Logo() {
  return (
    <Link href="/" className="flex items-center gap-2">
      <img src="/images/logo-icon.svg" alt="" className="w-8 h-8 rounded-full" />
      <span className="text-lg font-bold text-foreground">
        Vera<span className="text-muted-foreground font-medium">Fund</span>
      </span>
    </Link>
  );
}

// Shows which parts of Vera run on this device's GPU (private or hybrid mode) and whether
// the local model is loaded right now. Nothing shows in the cloud build.
async function AiBadge() {
  const chatLocal = llmProvider() === "ollama";
  const actionsLocal = agentLlmProvider() === "ollama";
  if (!chatLocal && !actionsLocal) return null;
  const status = await ollamaStatus();
  const gb = status && status.vramBytes > 0 ? ` · ${(status.vramBytes / 1e9).toFixed(1)} GB GPU` : "";
  const scope = chatLocal ? "On-device AI" : "On-device actions";
  return (
    <span
      data-testid="ai-mode"
      title={
        chatLocal
          ? "Vera's answers are generated by a language model running on this device's GPU."
          : "Vera picks actions with a language model on this device's GPU. Conversation uses Claude in the cloud."
      }
      className="inline-flex items-center gap-2 rounded-full border border-sky-500/40 bg-sky-500/10 px-3 py-1 text-xs font-semibold text-sky-800 dark:text-sky-300"
    >
      <span className={`h-2 w-2 rounded-full ${status?.loaded ? "bg-sky-500" : "bg-muted-foreground"}`} aria-hidden="true" />
      {scope} · {ollamaModel()}
      {status?.loaded ? gb : " · not loaded"}
    </span>
  );
}

export default async function AppLayout({ children }: { children: React.ReactNode }) {
  const workspaceId = await getWorkspaceId();
  if (!workspaceId) redirect("/");
  const workspace = await getWorkspace(workspaceId);
  if (!workspace) redirect("/?expired=1");
  const now = workspaceNow(workspace);
  const bellItems = (await getNotifications(workspaceId)).map((n) => ({
    id: n.id,
    kind: n.kind,
    title: n.title,
    body: n.body,
    read: n.read,
    when: formatDateTime(n.createdAt),
  }));
  const bell = <NotificationBell items={bellItems} />;

  return (
    <div className="min-h-screen bg-background md:flex">
      <aside className="hidden md:flex w-64 flex-shrink-0 border-r border-border bg-card flex-col sticky top-0 h-screen">
        <div className="px-6 pt-6 pb-5">
          <Logo />
        </div>
        <AppNav orientation="vertical" />
        <div className="m-3 space-y-2 rounded-xl border border-border bg-muted/50 p-4 text-xs text-muted-foreground">
          <p className="flex items-center gap-2 font-semibold text-foreground">
            <span className="flex h-6 w-6 items-center justify-center rounded-full bg-success/10 text-success">
              <ShieldCheck size={14} aria-hidden="true" />
            </span>
            Private workspace
          </p>
          <p className="leading-relaxed">
            {llmProvider() === "ollama"
              ? "Vera's language model runs on this device's GPU. Sandbox cards: no real money moves."
              : agentLlmProvider() === "ollama"
                ? "Vera chooses actions on this device's GPU. Sandbox cards: no real money moves."
                : "Your data stays private to this browser. Sandbox cards: no real money moves."}
          </p>
        </div>
      </aside>

      <div className="flex-1 min-w-0 flex flex-col">
        <header className="sticky top-0 z-30 space-y-3 border-b border-border bg-card px-4 py-3 shadow-[0_1px_0_rgba(38,28,18,0.02)] md:flex md:items-center md:justify-between md:gap-4 md:space-y-0 md:px-8">
          <div className="flex items-center justify-between gap-3 md:hidden">
            <Logo />
            <div className="flex items-center gap-2">
              {bell}
              <ThemeToggle />
            </div>
          </div>
          <div className="md:hidden">
            <AppNav orientation="horizontal" />
          </div>
          <div className="flex flex-wrap items-center gap-3">
            <AiBadge />
            <span
              className="inline-flex items-center gap-2 rounded-full border border-border bg-background px-3 py-1 text-sm text-muted-foreground"
              data-testid="demo-date"
            >
              <CalendarDays size={14} aria-hidden="true" className="text-primary" />
              <span>
                Today: <span className="font-medium text-foreground">{formatDate(now)}</span>
                {workspace.clockOffsetDays > 0 && ` (+${workspace.clockOffsetDays} days)`}
              </span>
            </span>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <form action={jumpAheadAction}>
              <ReturnTo />
              <SubmitButton variant="outline" pendingText="Jumping…">
                Jump ahead 8 days
              </SubmitButton>
            </form>
            <UserMenu />
            <div className="hidden md:flex items-center gap-2">
              {bell}
              <ThemeToggle />
            </div>
          </div>
        </header>

        <main className="app-canvas flex-1 p-4 pb-28 md:px-8 md:py-8 md:pb-28">{children}</main>
        <VeraDock />
      </div>
    </div>
  );
}
